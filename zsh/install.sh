#!/usr/bin/env bash
# install.sh — copy this repo's zsh config into ~/.zsh/
#
# The repo's zsh/ is copied into ~/.zsh/. Linux uses the system zshenv;
# macOS uses compatibility links because it does not ship a writable system
# zshenv location.
#
# Usage:
#   ./install.sh              # personal profile (default on every OS)
#   ./install.sh --assurant   # Assurant/Astra modules
#   ./install.sh --base       # explicit personal profile
#   ./install.sh --uninstall
#
# Safe to re-run; managed bootstrap blocks are replaced in place.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SOURCE_DIR="$REPO/zsh"         # the dir copied into ~/.zsh
TARGET_DIR="$HOME/.zsh"
OS="$(uname -s)"
USER_ZSHENV="$HOME/.zshenv"
# System zshenv locations to try, in order. First existing file wins, then
# first directory that exists. Debian/Ubuntu/WSL and Arch use /etc/zsh/zshenv;
# Fedora and upstream/default builds use /etc/zshenv.
SYS_ZSHENV_CANDIDATES=(
  "/etc/zsh/zshenv"
  "/etc/zshenv"
)
MARKER_BEGIN="# >>> zsh/install.sh managed block >>>"
MARKER_END="# <<< zsh/install.sh managed block <<<"
MALFORMED_MARKER_LINE='nstall.sh managed block >>>/,/# <<< zsh/install.sh managed block <<</d'
TS="$(date +%Y%m%d%H%M%S)"

# macOS has no /etc/zshenv or /etc/zsh/zshenv. Compatibility links provide
# the standard startup paths while the canonical files remain under ~/.zsh.
if [[ "$OS" == "Darwin" ]]; then
  USE_USER_ZSHENV=1
else
  USE_USER_ZSHENV=0
fi

# Files inside the repo that should never be copied to ~/.zsh.
# - plugins/ is auto-cloned on first launch by _zplugin_load
# - install.sh is a meta file, not config
# - README/CHEATSHEET are docs, optional
EXCLUDE_PATTERNS=(
  "plugins/"
  "install.sh"
  "README.md"
  ".gitignore"
)

detect_sys_zshenv() {
  local cand

  for cand in "${SYS_ZSHENV_CANDIDATES[@]}"; do
    if [[ -f "$cand" ]]; then
      SYS_ZSHENV="$cand"
      return
    fi
  done

  for cand in "${SYS_ZSHENV_CANDIDATES[@]}"; do
    if [[ -d "$(dirname "$cand")" ]]; then
      SYS_ZSHENV="$cand"
      return
    fi
  done

  SYS_ZSHENV="/etc/zshenv"
}

sed_in_place() {
  if [[ "$OS" == "Darwin" ]]; then
    sed -i '' -e "$1" "$2"
  else
    sed -i -e "$1" "$2"
  fi
}

# Personal profile is the default on every OS. Assurant modules are opt-in.
ASSURANT=0
UNINSTALL=0
for arg in "$@"; do
  case "$arg" in
    --assurant)
      ASSURANT=1
      ;;
    --base)
      ASSURANT=0
      ;;
    --uninstall) UNINSTALL=1 ;;
    -h|--help)
      sed -n '2,13p' "$0"
      exit 0
      ;;
    *)
      printf 'Unknown argument: %s\n' "$arg" >&2
      exit 1
      ;;
  esac
done

green()  { printf '\033[32m✓\033[0m %s\n' "$1"; }
yellow() { printf '\033[33m!\033[0m %s\n' "$1"; }
bold()   { printf '\033[1m%s\033[0m\n' "$1"; }

clean_malformed_managed_lines() {
  local target="$1" cleaned
  if ! grep -qF "$MALFORMED_MARKER_LINE" "$target"; then
    return 0
  fi

  cleaned="$(mktemp)"
  grep -vF "$MALFORMED_MARKER_LINE" "$target" > "$cleaned" || true
  mv "$cleaned" "$target"
}

if [[ "$USE_USER_ZSHENV" -eq 1 ]]; then
  SYS_ZSHENV="$USER_ZSHENV"
else
  detect_sys_zshenv
fi

# ---- sudo helper ---------------------------------------------------------
# Decide whether we can use sudo. We can use it if:
#   - we're root, OR
#   - we have passwordless sudo, OR
#   - we're in an interactive terminal (sudo can prompt for a password).
# In the non-interactive case without passwordless sudo, we print the
# block to add manually instead of failing partway.
SUDO=""
SUDO_OK=0
INTERACTIVE=0
[[ -t 0 && -t 1 ]] && INTERACTIVE=1

if [[ "$EUID" -eq 0 ]]; then
  SUDO_OK=1
elif command -v sudo >/dev/null 2>&1; then
  if sudo -n true 2>/dev/null; then
    SUDO="sudo"
    SUDO_OK=1
  elif [[ "$INTERACTIVE" -eq 1 ]]; then
    # Interactive: let sudo prompt for the password at write time.
    SUDO="sudo"
    SUDO_OK=1
  fi
fi

# ---- system zshenv block -------------------------------------------------
write_system_zshenv() {
  if [[ "$SUDO_OK" -ne 1 ]]; then
    yellow "Skipping $SYS_ZSHENV (no passwordless sudo)."
    yellow "Run install.sh in an interactive terminal, or add this to $SYS_ZSHENV manually:"
    yellow ""
    yellow '    if [[ -z "$XDG_CONFIG_HOME" ]]; then'
    yellow '        export XDG_CONFIG_HOME="$HOME/.config"'
    yellow '    fi'
    yellow '    if [[ -d "$HOME/.zsh" ]]; then'
    yellow '        export ZDOTDIR="$HOME/.zsh"'
    yellow '    fi'
    return 0
  fi

  local tmp
  tmp="$(mktemp)"
  # shellcheck disable=SC2064
  trap "rm -f '$tmp'" RETURN

  if [[ -f "$SYS_ZSHENV" ]]; then
    $SUDO cp "$SYS_ZSHENV" "$tmp"
    clean_malformed_managed_lines "$tmp"
    if grep -qF "$MARKER_BEGIN" "$tmp"; then
      sed_in_place "/$MARKER_BEGIN/,/$MARKER_END/d" "$tmp"
    fi
  fi

  {
    [[ -s "$tmp" ]] && cat "$tmp"
    printf '\n%s\n' "$MARKER_BEGIN"
    printf '# Auto-generated by zsh/install.sh on %s. Safe to remove manually.\n' "$(date -Iseconds)"
    printf 'if [[ -z "$XDG_CONFIG_HOME" ]]; then\n'
    printf '    export XDG_CONFIG_HOME="$HOME/.config"\n'
    printf 'fi\n'
    printf 'if [[ -d "$HOME/.zsh" ]]; then\n'
    printf '    export ZDOTDIR="$HOME/.zsh"\n'
    printf 'fi\n'
    printf '%s\n' "$MARKER_END"
  } > "$tmp"

  $SUDO install -m 644 "$tmp" "$SYS_ZSHENV"
  green "Updated $SYS_ZSHENV (ZDOTDIR=$TARGET_DIR)"
}

remove_managed_block_from_zshenv() {
  local target="$1"
  if [[ ! -f "$target" ]]; then return 0; fi
  if ! grep -qF "$MARKER_BEGIN" "$target" &&
    ! grep -qF "$MALFORMED_MARKER_LINE" "$target"; then
    return 0
  fi

  if [[ "$SUDO_OK" -ne 1 ]]; then
    yellow "Cannot remove managed block from $target (no sudo)."
    return 1
  fi

  local tmp
  tmp="$(mktemp)"
  $SUDO cp "$target" "$tmp"
  clean_malformed_managed_lines "$tmp"
  sed_in_place "/$MARKER_BEGIN/,/$MARKER_END/d" "$tmp"
  $SUDO install -m 644 "$tmp" "$target"
  rm -f "$tmp"
  yellow "Removed managed block from $target"
}

cleanup_inactive_zshenvs() {
  local cand
  [[ "$SUDO_OK" -eq 1 ]] || return 0

  for cand in "${SYS_ZSHENV_CANDIDATES[@]}"; do
    [[ "$cand" == "$SYS_ZSHENV" ]] && continue
    remove_managed_block_from_zshenv "$cand" || true
  done
}

remove_system_zshenv() {
  local cand failed=0

  for cand in "${SYS_ZSHENV_CANDIDATES[@]}"; do
    remove_managed_block_from_zshenv "$cand" || failed=1
  done

  return "$failed"
}

# ---- copy repo → ~/.zsh -------------------------------------------------
should_exclude() {
  local rel="$1"
  for pat in "${EXCLUDE_PATTERNS[@]}"; do
    if [[ "$rel" == "$pat"* || "$rel" == "$pat" ]]; then
      return 0
    fi
  done
  # SSH agent support belongs to the Assurant profile.
  if [[ "$rel" == "ssh-agent.zsh" && "$ASSURANT" -ne 1 ]]; then
    return 0
  fi
  if [[ "$rel" == "uv.zsh" && "$ASSURANT" -ne 1 ]]; then
    return 0
  fi
  # Assurant files are only included with --assurant
  if [[ "$rel" == work/* && "$ASSURANT" -ne 1 ]]; then
    return 0
  fi
  return 1
}

copy_repo() {
  mkdir -p "$TARGET_DIR"

  # If the user previously had a symlink here, remove it so we can copy
  # files into the path directly.
  if [[ -L "$TARGET_DIR" ]]; then
    rm "$TARGET_DIR"
    yellow "Removed legacy symlink at $TARGET_DIR"
  fi

  # Use git ls-files to get tracked files only (no plugins/, no .git/, etc.)
  local files
  files=$(git -C "$REPO" ls-files zsh/)

  # Build the set of paths we expect to exist after the copy.
  local -A expected
  while IFS= read -r src; do
    local rel="${src#zsh/}"
    should_exclude "$rel" && continue
    [[ -f "$REPO/$src" ]] || continue
    expected["$rel"]=1
  done <<< "$files"

  # Keep newly added local modules available before their first commit.
  [[ -f "$SOURCE_DIR/nvm.zsh" ]] && expected["nvm.zsh"]=1

  # CHEATSHEET.md contains Assurant commands; personal profile stays clean.
  [[ "$ASSURANT" -eq 1 && -f "$REPO/CHEATSHEET.md" ]] && expected["CHEATSHEET.md"]=1

  # Copy each tracked file in.
  local copied=0
  for rel in "${!expected[@]}"; do
    local dst="$TARGET_DIR/$rel"
    mkdir -p "$(dirname "$dst")"
    local src_path="$REPO/zsh/$rel"
    [[ "$rel" == "CHEATSHEET.md" ]] && src_path="$REPO/$rel"
    cp "$src_path" "$dst"
    copied=$((copied + 1))
  done

  # Remove files that USED to be tracked but no longer are. Walk the
  # installed tree and delete any regular file that isn't in $expected
  # and isn't user-created (plugins/, work/az.env).
  local removed=0
  if [[ -d "$TARGET_DIR" ]]; then
    while IFS= read -r -d '' f; do
      local rel="${f#$TARGET_DIR/}"
      # Skip excluded/auto-managed paths
      case "$rel" in
        plugins/*|starship.toml|work/az.env|.zshenv.uninstalled.*) continue ;;
      esac
      # Skip directories
      [[ -d "$f" ]] && continue
      # If it's in the expected set, keep it
      [[ -n "${expected[$rel]:-}" ]] && continue
      rm "$f"
      removed=$((removed + 1))
    done < <(find "$TARGET_DIR" -type f -print0 2>/dev/null)
  fi

  green "Copied $copied files from repo into $TARGET_DIR"
  if [[ "$removed" -gt 0 ]]; then
    yellow "Removed $removed stale file(s) that are no longer in the repo"
  fi
}

# Append ZSH_ASSURANT=1 to the installed .zshenv if --assurant was passed.
apply_assurant_flag() {
  local zshenv="$TARGET_DIR/.zshenv"
  if [[ ! -f "$zshenv" ]]; then
    [[ "$ASSURANT" -eq 1 ]] && yellow "Cannot enable --assurant: $zshenv not found"
    return
  fi

  if [[ "$ASSURANT" -ne 1 ]]; then
    if grep -qF 'export ZSH_ASSURANT=1' "$zshenv"; then
      sed_in_place '/^export ZSH_ASSURANT=1$/d' "$zshenv"
      yellow "Removed ZSH_ASSURANT=1 from installed .zshenv"
    fi
    return
  fi

  if ! grep -qF 'export ZSH_ASSURANT=1' "$zshenv"; then
    local tmp
    tmp="$(mktemp)"
    {
      printf '# Assurant modules enabled (Astra/Kubernetes/CA/SSH-agent).\n'
      printf 'export ZSH_ASSURANT=1\n\n'
      cat "$zshenv"
    } > "$tmp"
    install -m 644 "$tmp" "$zshenv"
    rm -f "$tmp"
    green "Set ZSH_ASSURANT=1 in installed .zshenv"
  fi
}

# ---- starship theme picker --------------------------------------------
# Themes live in $REPO/../starship/ (sibling of zsh/). At install time the
# user picks one, or sets ZSH_STARSHIP_THEME to skip the prompt.
STARSHIP_THEMES_DIR="$REPO/../starship"
STARSHIP_DEFAULT_THEME="nova"

list_starship_themes() {
  local f
  for f in "$STARSHIP_THEMES_DIR"/*.toml; do
    [[ -f "$f" ]] && basename "$f" .toml
  done | sort
}

pick_starship_theme() {
  local themes
  themes=($(list_starship_themes))
  if [[ ${#themes[@]} -eq 0 ]]; then
    yellow "No starship themes found in $STARSHIP_THEMES_DIR"
    return 1
  fi

  # If user supplied one, use it.
  if [[ -n "${ZSH_STARSHIP_THEME:-}" ]]; then
    printf '%s\n' "$ZSH_STARSHIP_THEME"
    return 0
  fi

  # In an interactive terminal, prompt.
  if [[ -t 0 && -t 1 ]]; then
    local i=1 choice
    printf '\nAvailable starship themes:\n'
    for t in "${themes[@]}"; do
      printf '  %d) %s\n' "$i" "$t"
      i=$((i+1))
    done
    printf '\n'
    read -r -p "Pick a theme [1-${#themes[@]}] (default: $STARSHIP_DEFAULT_THEME): " choice
    if [[ -z "$choice" ]]; then
      printf '%s\n' "$STARSHIP_DEFAULT_THEME"
    elif [[ "$choice" =~ ^[0-9]+$ ]] && (( choice >= 1 && choice <= ${#themes[@]} )); then
      printf '%s\n' "${themes[$((choice-1))]}"
    else
      yellow "Invalid choice '$choice' — using default"
      printf '%s\n' "$STARSHIP_DEFAULT_THEME"
    fi
    return 0
  fi

  # Non-interactive: use the default.
  printf '%s\n' "$STARSHIP_DEFAULT_THEME"
}

install_starship_theme() {
  [[ -d "$STARSHIP_THEMES_DIR" ]] || {
    yellow "No starship themes directory at $STARSHIP_THEMES_DIR — skipping"
    return 0
  }

  local theme source dest
  theme="$(pick_starship_theme)"
  source="$STARSHIP_THEMES_DIR/$theme.toml"
  dest="$TARGET_DIR/starship.toml"

  if [[ ! -f "$source" ]]; then
    yellow "Starship theme '$theme' not found at $source"
    yellow "Available: $(list_starship_themes | tr '\n' ' ')"
    return 1
  fi

  mkdir -p "$TARGET_DIR"
  cp "$source" "$dest"
  green "Installed starship theme: $theme"
}

# ---- compatibility links -----------------------------------------------
ensure_compatibility_links() {
  local legacy target name current

  mkdir -p "$HOME/.config"

  for name in .zshenv .zprofile .zshrc; do
    legacy="$HOME/$name"
    target="$TARGET_DIR/$name"
    [[ -f "$target" ]] || continue

    if [[ -L "$legacy" ]]; then
      current="$(readlink "$legacy")"
      [[ "$current" == "$target" ]] && continue
    elif [[ ! -e "$legacy" ]]; then
      :
    fi

    if [[ -e "$legacy" || -L "$legacy" ]]; then
      mv "$legacy" "$legacy.bak.$TS"
      yellow "Backed up existing $legacy → $legacy.bak.$TS"
    fi
    ln -s "$target" "$legacy"
    green "Linked $legacy → $target"
  done

  legacy="$HOME/.config/zsh"
  target="$TARGET_DIR"
  if [[ -L "$legacy" ]]; then
    current="$(readlink "$legacy")"
    [[ "$current" == "$target" ]] && legacy=""
  fi
  if [[ -n "$legacy" ]]; then
    if [[ -e "$legacy" || -L "$legacy" ]]; then
      mv "$legacy" "$legacy.bak.$TS"
      yellow "Backed up existing $legacy → $legacy.bak.$TS"
    fi
    ln -s "$target" "$legacy"
    green "Linked $legacy → $target"
  fi

  legacy="$HOME/.config/starship.toml"
  target="$TARGET_DIR/starship.toml"
  [[ -f "$target" ]] || return 0
  if [[ -L "$legacy" ]]; then
    current="$(readlink "$legacy")"
    [[ "$current" == "$target" ]] && return 0
  elif [[ -e "$legacy" ]]; then
    mv "$legacy" "$legacy.bak.$TS"
    yellow "Backed up existing $legacy → $legacy.bak.$TS"
  fi
  ln -s "$target" "$legacy"
  green "Linked $legacy → $target"
}

remove_compatibility_links() {
  local legacy target name

  for name in .zshenv .zprofile .zshrc; do
    legacy="$HOME/$name"
    target="$TARGET_DIR/$name"
    [[ -L "$legacy" && "$(readlink "$legacy")" == "$target" ]] || continue
    rm "$legacy"
  done

  legacy="$HOME/.config/zsh"
  target="$TARGET_DIR"
  [[ -L "$legacy" && "$(readlink "$legacy")" == "$target" ]] && rm "$legacy"

  legacy="$HOME/.config/starship.toml"
  target="$TARGET_DIR/starship.toml"
  [[ -L "$legacy" && "$(readlink "$legacy")" == "$target" ]] && rm "$legacy"
}

# =========================================================================
if [[ "$UNINSTALL" -eq 1 ]]; then
  bold "==> Uninstalling"
  remove_compatibility_links
  if [[ -d "$TARGET_DIR" || -L "$TARGET_DIR" ]]; then
    if [[ -L "$TARGET_DIR" ]]; then
      rm "$TARGET_DIR"
    else
      # Back up the user's installed config rather than deleting it.
      mv "$TARGET_DIR" "$TARGET_DIR.uninstalled.$TS"
    fi
    yellow "Removed $TARGET_DIR (backup at $TARGET_DIR.uninstalled.$TS if it was a dir)"
  fi
  remove_system_zshenv
  bold "==> Done"
  exit 0
fi

bold "==> Installing"
if [[ "$USE_USER_ZSHENV" -eq 1 ]]; then
  :
else
  write_system_zshenv
  cleanup_inactive_zshenvs
fi
copy_repo
install_starship_theme
apply_assurant_flag
ensure_compatibility_links

if [[ "$ASSURANT" -eq 1 ]]; then
  PROFILE="personal + assurant"
else
  PROFILE="personal"
fi

echo ""
bold "==> Done"
echo "  Open a new terminal or run:  exec zsh -l"
echo ""
echo "  Layout:"
echo "    Profile:                    $PROFILE"
if [[ "$USE_USER_ZSHENV" -eq 1 ]]; then
  echo "    ~/.zshenv/.zprofile/.zshrc → compatibility links"
else
  echo "    $SYS_ZSHENV            → sets ZDOTDIR (managed)"
fi
echo "    $TARGET_DIR              → copied from the repo"
echo "    $TARGET_DIR/.zshenv     → XDG vars, starship, Assurant env (if enabled)"
echo "    $TARGET_DIR/.zshrc      → all modules + starship"
echo "    ~/.config/zsh           → compatibility link"
echo "    ~/.config/starship.toml → compatibility link"
echo ""
echo "  First launch auto-installs missing plugins:"
echo "    zsh-autosuggestions"
echo "    zsh-history-substring-search"
echo "    fast-syntax-highlighting"
echo ""
echo "  To re-sync after editing the repo:  ./install.sh [--assurant|--base]"
echo "  To enable Assurant modules:         ./install.sh --assurant"
echo "  To keep the personal profile:       ./install.sh --base"
echo "  To remove everything:               ./install.sh --uninstall"
echo ""
echo "  Recommended tools to install:"
echo "    eza bat fd-find ripgrep fzf zoxide starship direnv lf nvim"

if [[ "$ASSURANT" -eq 1 ]]; then
  echo ""
  bold "==> Action required: Azure IDs"
  echo "  Copy the template and fill in the IDs:"
  echo "      cp $TARGET_DIR/work/az.env.example $TARGET_DIR/work/az.env"
  echo "      \$EDITOR $TARGET_DIR/work/az.env"
  echo ""
  echo "  Then replace the placeholder values:"
  echo ""
  echo "      export AZ_TENANT_ID=\"<your-tenant-guid>\""
  echo "      export AZ_SUBSCRIPTION_ID=\"<your-subscription-guid>\""
  echo ""
  echo "  Find them with:"
  echo "      az account tenant list   --query '[].tenantId' -o tsv"
  echo "      az account list          --query '[].{name:name,id:id}' -o table"
  echo ""
  echo "  az.env is git-ignored so your real IDs stay local to this machine."
fi
